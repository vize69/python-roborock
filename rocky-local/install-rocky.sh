#!/usr/bin/env bash
# Rocky Local 0.1.0: no restart, no Docker access, no credential changes.
set -euo pipefail
action=${1:---check}
case "$action" in --check|--apply|--rollback) ;; *) echo 'Usage: bash install-rocky.sh --check|--apply|--rollback'; exit 2;; esac
root=${ROCKY_CONFIG_ROOT:-/config}
if [[ ! -f "$root/configuration.yaml" && -z "${ROCKY_CONFIG_ROOT:-}" && -f /homeassistant/configuration.yaml ]]; then root=/homeassistant; fi
[[ -f "$root/configuration.yaml" ]] || { echo 'Home Assistant configuration.yaml not found.'; exit 1; }
for command in ha jq tar base64 sha256sum mktemp mv; do command -v "$command" >/dev/null || { echo "Missing command: $command"; exit 1; }; done
target="$root/custom_components/roborock"
mkdir -p "$root/exchange"
stage=$(mktemp -d "$root/exchange/rocky-stage.XXXXXX")
trap 'rm -rf "$stage"' EXIT
payload() {
  sed '1,/^__ROCKY_PAYLOAD__$/d' "${BASH_SOURCE[0]}" | base64 -d
}
payload > "$stage/payload.tar.gz"
echo '830ac2a75ae41bd652a59244a6d543598f4605194878fe0ebb6cf94501b80baa  payload.tar.gz' > "$stage/payload.sha256"
(cd "$stage" && sha256sum -c payload.sha256 >/dev/null)
tar -xzf "$stage/payload.tar.gz" -C "$stage"
(cd "$stage/custom_components/roborock" && sha256sum -c SHA256SUMS >/dev/null)
if [[ "$action" == --rollback ]]; then
  [[ -d "$target" && ! -L "$target" ]] || { echo 'No Rocky installation to remove.'; exit 1; }
  cmp "$stage/custom_components/roborock/SHA256SUMS" "$target/SHA256SUMS" >/dev/null || { echo 'Different version: refusing rollback.'; exit 1; }
  (cd "$target" && sha256sum -c SHA256SUMS >/dev/null) || { echo 'Files changed: refusing rollback.'; exit 1; }
  backup=$(mktemp -d "$root/exchange/rocky-disabled.XXXXXX")
  mv "$target" "$backup/roborock"
  if ! ha core check; then mv "$backup/roborock" "$target"; echo 'Configuration check failed; installation restored.'; exit 1; fi
  echo "Custom integration removed; preserved in $backup. Restart Home Assistant separately to use the official integration."
  exit 0
fi
version=$(ha core info --raw-json | jq -r '.data.version // .version // empty')
[[ "$version" == 2026.10.0b3 ]] || { echo "This package targets HA 2026.10.0b3; found $version. Review required."; exit 1; }
if [[ -e "$target" || -L "$target" ]]; then
  if [[ ! -L "$target" ]] && cmp "$stage/custom_components/roborock/SHA256SUMS" "$target/SHA256SUMS" >/dev/null 2>&1 && (cd "$target" && sha256sum -c SHA256SUMS >/dev/null); then
    echo 'Rocky Local 0.1.0 is already installed. No files changed.'; exit 0
  fi
  echo 'An existing custom Roborock integration is present. Refusing to overwrite it.'; exit 1
fi
shopt -s nullglob
for manifest in "$root"/custom_components/*/manifest.json; do
  if jq -e 'any(.requirements[]?; test("python[-_]roborock"; "i"))' "$manifest" >/dev/null; then
    echo "Another integration requires python-roborock: $manifest. Review dependency compatibility first."; exit 1
  fi
done
if [[ "$action" == --check ]]; then echo 'Preflight OK. Run with --apply to install; no restart is performed.'; exit 0; fi
mkdir -p "$root/custom_components"
mv "$stage/custom_components/roborock" "$target"
if ! ha core check; then
  mv "$target" "$stage/failed-install"
  echo 'Configuration check failed; newly installed integration removed. No restart performed.'
  exit 1
fi
echo 'Rocky Local 0.1.0 installed and configuration checked. NOT ACTIVE until Home Assistant is restarted separately.'
exit 0
